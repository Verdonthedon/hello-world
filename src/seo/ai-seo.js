// AI SEO / GEO skill — implements .claude/skills/ai-seo-geo.
// Three capabilities:
//   1. buildSchemas()  — the full JSON-LD stack (LocalBusiness, FAQPage, WebSite,
//      BreadcrumbList, speakable) injected at render time
//   2. writeGeoArtifacts() — llms.txt + robots.txt (AI-crawler allowlist) per site
//   3. auditAiSeo()   — passage-level GEO audit, 0-100, with actionable gaps.
//      Runs on OUR generated sites (gate) and on PROSPECT sites (sales proof).
import fs from 'node:fs';
import path from 'node:path';
import { clamp } from '../util/helpers.js';

export function canonicalUrl(lead, analysis) {
  return lead.website && !/business\.site|wixsite|weebly|facebook|instagram/.test(lead.website)
    ? lead.website
    : `https://www.${(analysis.businessName || lead.name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.com`;
}

export function buildSchemas({ lead, analysis, copy, url }) {
  const name = analysis.businessName;
  const showRating = lead.rating && lead.rating >= 4.5 && lead.reviewCount >= 10;
  const localBusiness = {
    '@context': 'https://schema.org',
    '@type': 'LocalBusiness',
    '@id': `${url}#business`,
    name,
    description: analysis.valueProp,
    url,
    telephone: lead.phone || undefined,
    address: {
      '@type': 'PostalAddress',
      streetAddress: lead.address || undefined,
      addressLocality: lead.city || undefined,
      addressRegion: lead.region || undefined,
      addressCountry: lead.country || undefined,
    },
    areaServed: analysis.location,
    ...(showRating
      ? { aggregateRating: { '@type': 'AggregateRating', ratingValue: String(lead.rating), reviewCount: String(lead.reviewCount) } }
      : {}),
    makesOffer: (analysis.services || []).map((s) => ({
      '@type': 'Offer',
      itemOffered: { '@type': 'Service', name: typeof s === 'string' ? s : s.name },
    })),
  };
  const faqPage = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: (copy.faq || []).map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
  const webSite = {
    '@context': 'https://schema.org',
    '@type': 'WebPage',
    '@id': `${url}#page`,
    url,
    name: `${name} | ${analysis.category} in ${analysis.location}`,
    about: { '@id': `${url}#business` },
    speakable: { '@type': 'SpeakableSpecification', cssSelector: ['.hero-h1', '.definition', '.faq-a'] },
  };
  const breadcrumbs = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: url },
      { '@type': 'ListItem', position: 2, name: 'Services', item: `${url}#services` },
      { '@type': 'ListItem', position: 3, name: 'FAQ', item: `${url}#faq` },
    ],
  };
  return [localBusiness, faqPage, webSite, breadcrumbs];
}

// AI crawler allowlist — crawlers that cite sources get an explicit welcome.
const AI_CRAWLERS = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-Web', 'PerplexityBot', 'Google-Extended', 'GoogleOther', 'Applebot-Extended', 'cohere-ai'];

export function writeGeoArtifacts({ dir, lead, analysis, copy, url }) {
  const robots = [
    '# AI-crawler friendly — generated by LeadFlow Pro (GEO skill)',
    ...AI_CRAWLERS.flatMap((b) => [`User-agent: ${b}`, 'Allow: /', '']),
    'User-agent: *',
    'Allow: /',
    '',
    `Sitemap: ${url.replace(/\/$/, '')}/sitemap.xml`,
    '',
  ].join('\n');

  const llms = [
    `# ${analysis.businessName}`,
    '',
    `> ${analysis.businessName} is a ${analysis.category.toLowerCase()} in ${analysis.location} — ${analysis.valueProp}`,
    '',
    `- Phone: ${lead.phone || 'see website'}`,
    `- Address: ${lead.address || analysis.location}`,
    `- Service area: ${analysis.location} and surrounding communities`,
    '',
    '## Services',
    ...(analysis.services || []).map((s) => `- ${typeof s === 'string' ? s : s.name}`),
    '',
    '## Frequently asked questions',
    ...(copy.faq || []).flatMap((f) => [`### ${f.q}`, f.a, '']),
    '## Booking',
    `Schedule a consultation: ${url}#book`,
    '',
  ].join('\n');

  fs.writeFileSync(path.join(dir, 'robots.txt'), robots);
  fs.writeFileSync(path.join(dir, 'llms.txt'), llms);
  return { robots: 'robots.txt', llms: 'llms.txt' };
}

// Passage-level GEO audit of rendered HTML. Used as gate for our sites and as
// the before/after proof against prospect sites.
export function auditAiSeo(html, { businessName } = {}) {
  const text = html.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ');
  const checks = {
    titleLength: (() => {
      const m = html.match(/<title[^>]*>([^<]*)<\/title>/i);
      return !!m && m[1].length >= 25 && m[1].length <= 75;
    })(),
    metaDescription: (() => {
      const m = html.match(/name=["']description["'][^>]+content=["']([^"']*)["']/i);
      return !!m && m[1].length >= 100 && m[1].length <= 340;
    })(),
    canonical: /rel=["']canonical["']/i.test(html),
    localBusinessSchema: /"@type"\s*:\s*"LocalBusiness"/.test(html),
    faqSchema: /"@type"\s*:\s*"FAQPage"/.test(html),
    breadcrumbSchema: /"@type"\s*:\s*"BreadcrumbList"/.test(html),
    speakable: /SpeakableSpecification/.test(html),
    definitionFirst: /class=["'][^"']*definition/.test(html),
    questionHeadings: (html.match(/<h[23][^>]*>[^<]*\?/gi) || []).length >= 2,
    selfContainedAnswers: (() => {
      const answers = [...html.matchAll(/class=["']faq-a["'][^>]*>([\s\S]*?)<\//g)].map((m) => m[1]);
      if (!answers.length) return false;
      const entityNamed = businessName ? answers.filter((a) => a.includes(businessName)).length : answers.length;
      return answers.every((a) => a.replace(/<[^>]+>/g, '').split(/\s+/).length >= 25) && entityNamed >= 2;
    })(),
    substantiveContent: (text.match(/\b\w+\b/g) || []).length >= 450,
    entityConsistency: businessName ? (html.split(businessName).length - 1) >= 6 : true,
    mobileViewport: /name=["']viewport["']/.test(html),
    openGraph: /property=["']og:title["']/.test(html),
  };
  const weights = {
    titleLength: 6, metaDescription: 8, canonical: 4, localBusinessSchema: 12,
    faqSchema: 10, breadcrumbSchema: 5, speakable: 6, definitionFirst: 10,
    questionHeadings: 9, selfContainedAnswers: 10, substantiveContent: 8,
    entityConsistency: 6, mobileViewport: 3, openGraph: 3,
  };
  const gapLabels = {
    titleLength: 'title tag missing or badly sized (25-75 chars)',
    metaDescription: 'meta description missing or badly sized (100-340 chars)',
    canonical: 'no canonical URL',
    localBusinessSchema: 'no LocalBusiness JSON-LD',
    faqSchema: 'no FAQPage JSON-LD',
    breadcrumbSchema: 'no BreadcrumbList JSON-LD',
    speakable: 'no speakable specification for voice/AI assistants',
    definitionFirst: 'no definition-first intro passage (who/what/where in one quotable sentence)',
    questionHeadings: 'fewer than 2 question-style headings (how users ask AI assistants)',
    selfContainedAnswers: 'FAQ answers too thin or not entity-named (RAG passages must stand alone)',
    substantiveContent: 'thin content — AI engines skip pages without substance',
    entityConsistency: 'business name not used consistently across the page',
    mobileViewport: 'no mobile viewport',
    openGraph: 'no Open Graph tags',
  };
  let score = 0;
  const gaps = [];
  for (const [k, ok] of Object.entries(checks)) {
    if (ok) score += weights[k];
    else gaps.push(gapLabels[k]);
  }
  return { score: clamp(score, 0, 100), gaps, checks };
}

export default { buildSchemas, writeGeoArtifacts, auditAiSeo, canonicalUrl };
